/**
 * Writes each interaction's source into a TypeScript module.
 *
 * The page used to read these files with fs.readFile at build time, but
 * Next's static analysis cannot bound a dynamic path, so it traced the entire
 * project into the serverless bundle — every source file and the public
 * folder shipped as server code. A generated module is a plain import: the
 * code shown is still the real source, and nothing extra is deployed.
 *
 * Runs automatically before build and dev via the `prebuild` script.
 */
import { readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";

const ROOT = process.cwd();
const DIR = path.join(ROOT, "src/interactions");
const OUT = path.join(DIR, "sources.generated.ts");

const entries = await readdir(DIR, { withFileTypes: true });
const folders = entries
  .filter((e) => e.isDirectory())
  .map((e) => e.name)
  .sort();

const sources = {};
for (const folder of folders) {
  const rel = `src/interactions/${folder}/index.tsx`;
  try {
    sources[folder] = await readFile(path.join(ROOT, rel), "utf8");
  } catch {
    // A folder without an index.tsx is not an interaction; skip it quietly.
  }
}

const body = Object.entries(sources)
  .map(([key, code]) => `  ${JSON.stringify(key)}: ${JSON.stringify(code)},`)
  .join("\n");

await writeFile(
  OUT,
  `// Generated by scripts/generate-interaction-sources.mjs — do not edit.\n` +
    `// Run \`npm run gen:sources\` (or any build) to refresh.\n\n` +
    `export const INTERACTION_SOURCES: Record<string, string> = {\n${body}\n};\n`,
  "utf8",
);

console.log(
  `✓ Interaction sources: ${Object.keys(sources).length} (${Object.keys(sources).join(", ")})`,
);
